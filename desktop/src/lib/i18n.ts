export const DICTIONARIES: Record<Language, Record<MessageKey, string>> = { fa, en };

export function translate(
  language: Language,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  let value = DICTIONARIES[language][key] ?? en[key] ?? String(key);
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}
